"""Rebuild IHAYO's original contour/seed identity. Optional asset tooling: fonttools[woff]."""
from pathlib import Path
import json
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'public'/'brand'
OUT.mkdir(parents=True,exist_ok=True)
FONT=ROOT/'node_modules/@fontsource-variable/dm-sans/files/dm-sans-latin-wght-normal.woff2'
FIELDS='M7 55V23C7 14.163 14.163 7 23 7H55V14H23C18.029 14 14 18.029 14 23V55ZM22 55V32C22 26.477 26.477 22 32 22H55V29H32C30.343 29 29 30.343 29 32V55ZM37 55V41C37 38.791 38.791 37 41 37H55V44H44V55Z'
SEED='M48 53C48 49.134 51.134 46 55 46H58V49C58 52.866 54.866 56 51 56H48Z'

def lettering(text,size,weight,tracking):
 source=TTFont(FONT)
 axes={a.axisTag for a in source['fvar'].axes}
 settings={k:v for k,v in {'wght':weight,'opsz':32 if weight>=600 else 14}.items() if k in axes}
 font=instantiateVariableFont(source,settings,inplace=False)
 glyphs=font.getGlyphSet();cmap=font.getBestCmap();scale=size/font['head'].unitsPerEm
 svg=SVGPathPen(glyphs);bounds=BoundsPen(glyphs);x=0
 for i,c in enumerate(text):
  if i and text[i-1:i+1] in ['HA','AY','YO']:x-=.5
  name=cmap[ord(c)];matrix=(scale,0,0,-scale,x,size)
  glyphs[name].draw(TransformPen(svg,matrix));glyphs[name].draw(TransformPen(bounds,matrix))
  x+=font['hmtx'][name][0]*scale+tracking
 x0,y0,x1,y1=bounds.bounds
 # A normalized, outlined wordmark has no installed-font dependency.
 return svg.getCommands(),[round(v,4) for v in (x0,y0,x1-x0,y1-y0)]

WORD,WB=lettering('IHAYO',42,600,2.6)
TAG,TB=lettering('Growing together.',16,400,0)
def wrap(content,w,h,title):return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" role="img"><title>{title}</title>{content}</svg>\n'
def symbol(ink,seed):return f'<path fill="{ink}" d="{FIELDS}"/><path fill="{seed}" d="{SEED}"/>'
def word(ink):return f'<path fill="{ink}" d="{WORD}" transform="translate({-WB[0]} {-WB[1]})"/>'
def horizontal(ink,seed):
 return f'<g transform="translate(0 4)">{symbol(ink,seed)}</g><g transform="translate(84 13)">{word(ink)}</g><path fill="{ink}" d="{TAG}" transform="translate({84-TB[0]} {52-TB[1]})"/>'
for name,ink,seed in [('light','#245A43','#A87728'),('dark','#F7F4EC','#D5A34D'),('mono','#071D2D','#071D2D'),('mono-white','#FFFFFF','#FFFFFF')]:
 (OUT/f'ihayo-symbol-{name}.svg').write_text(wrap(symbol(ink,seed),64,64,'IHAYO field contours and seed'),encoding='utf-8')
 (OUT/f'ihayo-horizontal-{name}.svg').write_text(wrap(horizontal(ink,seed),round(84+WB[2]+5,2),72,'IHAYO. Growing together.'),encoding='utf-8')
(OUT/'ihayo-wordmark.svg').write_text(wrap(word('#071D2D'),WB[2],WB[3],'IHAYO'),encoding='utf-8')
icon='<rect width="64" height="64" rx="14" fill="#071D2D"/><g transform="translate(6 6) scale(.8125)">'+symbol('#F7F4EC','#D5A34D')+'</g>'
(OUT/'ihayo-app-icon.svg').write_text(wrap(icon,64,64,'IHAYO'),encoding='utf-8')
(ROOT/'src/app/icon.svg').write_text(wrap(icon,64,64,'IHAYO'),encoding='utf-8')
data={'fields':FIELDS,'seed':SEED,'wordmark':WORD,'wordBounds':WB}
(ROOT/'src/lib/brand.ts').write_text('// Original IHAYO contour/seed geometry. Generated by scripts/generate-brand.py.\nexport const brandGeometry = '+json.dumps(data)+' as const;\n',encoding='utf-8')
print(json.dumps({'wordmark_bounds':WB,'assets':len(list(OUT.glob('*.svg')))}))
